class FakeProvider:
    name, model, supports_tools = "fake", "fake-1", True

    def __init__(self, replies):
        self.replies = list(replies)
        self.calls = []

    def chat(self, system, transcript, tools):
        self.calls.append((system, list(transcript), [t.name for t in tools]))
        return self.replies.pop(0)


@pytest.fixture
def console(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    rng = np.random.default_rng(0)
    tr = Trace((rng.normal(0, 1e-8, 36_000) / 1.59e-9).astype(np.int32),
               header={"network": "RD", "station": "SN270", "channel": "HHZ",
                       "sampling_rate": 100.0, "starttime": UTCDateTime(0)})
    Stream([tr]).write("v.mseed", format="MSEED")
    answers = []
    con = OnTheSignalConsole(files=["v.mseed"], config=Config(),
                             ask=lambda label, d: answers.pop(0) if answers else "", forms=False)
    con.execute('S1.unit = "m/s"; S1.sensitivity = 1.59e-9')
    con.answers = answers
    return con


