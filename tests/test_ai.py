def test_tool_call_runs_analysis(console):
    provider = FakeProvider([
        Reply("", [ToolCall("c1", "lnm", {"signal": "S1"})]),
        Reply("The noise is above the NLNM.", []),
    ])
    assistant = Assistant(console, provider)
    answer = assistant.ask("compare the noise of S1 with the LNM")
    assert answer == "The noise is above the NLNM."
    assert console.session.results[-1].kind == "lnm"
    tool_message = provider.calls[1][1][-1]
    assert tool_message["role"] == "tool" and '"ok": true' in tool_message["content"]
    assert "lnm" in provider.calls[0][2] and "run_script" in provider.calls[0][2]
    assert "S1" in provider.calls[0][0]  # session summary in the system prompt


