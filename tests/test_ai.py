"""AI assistant with a scripted fake provider (no network)."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
from obspy import Stream, Trace, UTCDateTime

from onthesignal.ai import Assistant, Reply, ToolCall, agent_doc, init_context, system_prompt
from onthesignal.ai.providers import AnthropicProvider, OllamaProvider, OpenAIProvider
from onthesignal.cli.console import OnTheSignalConsole
from onthesignal.core.config import Config
from onthesignal.core.registry import commands


class FakeProvider:
    name, model, supports_tools = "fake", "fake-1", True

    def __init__(self, replies):
        self.replies = list(replies)
        self.calls = []

    def chat(self, system, transcript, tools):
        self.calls.append((system, list(transcript), [t.name for t in tools]))
        return self.replies.pop(0)


@pytest.fixture
def console(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    rng = np.random.default_rng(0)
    tr = Trace((rng.normal(0, 1e-8, 36_000) / 1.59e-9).astype(np.int32),
               header={"network": "RD", "station": "SN270", "channel": "HHZ",
                       "sampling_rate": 100.0, "starttime": UTCDateTime(0)})
    Stream([tr]).write("v.mseed", format="MSEED")
    answers = []
    con = OnTheSignalConsole(files=["v.mseed"], config=Config(),
                             ask=lambda label, d: answers.pop(0) if answers else "", forms=False)
    con.execute('S1.unit = "m/s"; S1.sensitivity = 1.59e-9')
    con.answers = answers
    return con


def test_agent_doc_covers_every_command():
    doc = agent_doc()
    for cmd in commands():
        assert f"`{cmd.name}(" in doc
    assert "When to use" in doc and "LNM" in doc


def test_tool_call_runs_analysis(console):
    provider = FakeProvider([
        Reply("", [ToolCall("c1", "lnm", {"signal": "S1"})]),
        Reply("The noise is above the NLNM.", []),
    ])
    assistant = Assistant(console, provider)
    answer = assistant.ask("compare the noise of S1 with the LNM")
    assert answer == "The noise is above the NLNM."
    assert console.session.results[-1].kind == "lnm"
    tool_message = provider.calls[1][1][-1]
    assert tool_message["role"] == "tool" and '"ok": true' in tool_message["content"]
    assert "lnm" in provider.calls[0][2] and "run_script" in provider.calls[0][2]
    assert "S1" in provider.calls[0][0]  # session summary in the system prompt


def test_confirmation_required_for_scripts(console):
    provider = FakeProvider([
        Reply("", [ToolCall("c1", "run_script", {"name": "x", "signals": ["S1"]})]),
        Reply("ok", []),
    ])
    console.answers.append("n")
    Assistant(console, provider).ask("run my script")
    assert "refused" in provider.calls[1][1][-1]["content"]


def test_errors_are_returned_to_the_model(console):
    provider = FakeProvider([
        Reply("", [ToolCall("c1", "noise", {"signal": "S9"})]),
        Reply("Signal S9 does not exist.", []),
    ])
    Assistant(console, provider).ask("noise of S9")
    assert "Unknown signal" in provider.calls[1][1][-1]["content"]


def test_script_generation(console):
    code = ('```python\n"""\nName        : rms_ai\nDescription : test\n"""\n'
            "from onthesignal import Param, Result\nPARAMS = []\n\n"
            "def run(signals, **params):\n    return Result('rms_ai')\n```")
    provider = FakeProvider([Reply(code, [])])
    path = Assistant(console, provider).generate_script("rms_ai", "compute something")
    text = path.read_text()
    assert text.startswith("# Generated by AI (fake, fake-1,")
    from onthesignal.scripts import load_script

    assert load_script("rms_ai").description == "test"


